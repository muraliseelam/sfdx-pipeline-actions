#!/usr/bin/env bash
#
# cut-release.sh — create a release tag that pins its own internal references.
#
# WHY THIS EXISTS
#
# The reusable workflows in this repository call this repository's own composite
# actions by full name, and on `main` every one of those references reads
# `@main`. GitHub does not allow expressions in `uses:`, so a reference cannot
# say "whatever ref I was called as".
#
# That means tagging `main` directly produces a BROKEN release: the entry-point
# workflow is frozen at the tag, but every action it invokes still resolves to
# the moving `main` branch. A consumer pinning `@v1` would be pinned in name
# only, and would silently pick up unreleased changes.
#
# So each release tag carries one extra commit, off `main`, that rewrites every
# internal reference to point at the tag itself. `main` keeps `@main`; only
# tags are self-referential. That commit is never merged back.
#
# Usage:
#   ./scripts/cut-release.sh v1.2.0 [--push]
#   ./scripts/cut-release.sh v1     [--push]     # move a major alias

set -euo pipefail

TAG="${1:-}"
PUSH="${2:-}"

if [[ -z "$TAG" ]]; then
  echo "Usage: $0 <tag> [--push]" >&2
  exit 1
fi

cd "$(dirname "$0")/.."

if [[ -n "$(git status --porcelain)" ]]; then
  echo "Working tree is not clean. Commit or stash first." >&2
  exit 1
fi

BASE="$(git rev-parse --abbrev-ref HEAD)"
START="$(git rev-parse HEAD)"

cleanup() {
  git checkout -q "$BASE" 2>/dev/null || true
  git branch -D "release-tmp-${TAG}" 2>/dev/null || true
}
trap cleanup EXIT

echo "Cutting ${TAG} from ${BASE} (${START:0:8})"

git checkout -q -b "release-tmp-${TAG}"

# Rewrite every internal reference from its current ref to this tag.
CHANGED=$(python3 - "$TAG" <<'PY'
import re, pathlib, sys
tag = sys.argv[1]
pat = re.compile(r'([A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/(?:\.github/workflows|sf-pipeline)/[^@\s]+)@[A-Za-z0-9._-]+')
n = 0
for p in list(pathlib.Path('.github').rglob('*.yml')) + list(pathlib.Path('sf-pipeline').rglob('*.yml')):
    o = p.read_text()
    t, k = pat.subn(lambda m: f"{m.group(1)}@{tag}", o)
    if k and t != o:
        p.write_text(t)
        n += k
print(n)
PY
)

echo "  rewrote ${CHANGED} internal reference(s) to @${TAG}"

if [[ -z "$(git status --porcelain)" ]]; then
  echo "Nothing changed — refusing to tag, this would be indistinguishable from tagging main." >&2
  exit 1
fi

git add -A
git commit -q -m "release: pin internal references to ${TAG}

Generated by scripts/cut-release.sh. Not merged back into ${BASE}."

git tag -f -a "$TAG" -m "Release ${TAG}"
echo "  tagged ${TAG} -> $(git rev-parse --short HEAD)"

git checkout -q "$BASE"

echo
"$(dirname "$0")/verify-tag.sh" "$TAG"

if [[ "$PUSH" == "--push" ]]; then
  git push -f origin "refs/tags/${TAG}"
  echo "Pushed ${TAG}."
else
  echo
  echo "Dry run complete. Push with:  git push -f origin refs/tags/${TAG}"
fi
